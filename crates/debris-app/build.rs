//! Bakes the logo and the version into the executable as a Windows resource.
//!
//! The window icon is not a window property on Windows. GPUI's Windows backend has no
//! icon argument at all — it asks the *executable* for one
//! (`LoadImageW(module, PCWSTR(1), IMAGE_ICON, ..)` in `gpui_windows`), which is why
//! the taskbar, Alt-Tab and Explorer all show whatever `1 ICON` holds in the resource
//! section. A resource is a link-time thing, so it needs a build script.
//!
//! The version comes along for the same reason and from the same place: the release
//! workflow stamps the tag's CalVer into `[workspace.package].version` before it
//! builds, Cargo hands that to the build script as `CARGO_PKG_VERSION`, and the
//! VERSIONINFO block below is what Explorer's Details tab reads. So the tag, the exe's
//! properties, and the string on the status rail are one number.
//!
//! `embed-resource` is already in the dependency graph through GPUI's own
//! `windows-manifest` feature, so this adds no new crate to build.
//!
//! The second job is [`embed_runtime_data`]: the data files the app reads at runtime
//! are baked into the binary too, because the release is one exe that has to work with
//! nothing beside it.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=../../assets/debris.ico");
    // Re-stamp the VERSIONINFO when the manifest's version moves.
    println!("cargo:rerun-if-env-changed=CARGO_PKG_VERSION");

    // Not a Windows-only concern: the app needs its data wherever it is built.
    embed_runtime_data();

    // A build script is a host binary, so its own `cfg(target_os)` says nothing about
    // what we are compiling *for*. Ask Cargo instead.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }

    let icon = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets/debris.ico");
    let icon = icon
        .canonicalize()
        .expect("assets/debris.ico should exist in the source tree");
    let icon = icon.to_string_lossy().replace('\\', "\\\\");

    let version = std::env::var("CARGO_PKG_VERSION").expect("Cargo always sets the version");
    let mut components = version
        .split('.')
        .map(|part| part.parse::<u16>().unwrap_or(0))
        .chain(std::iter::repeat(0));
    let numeric = format!(
        "{},{},{},{}",
        components.next().unwrap_or(0),
        components.next().unwrap_or(0),
        components.next().unwrap_or(0),
        components.next().unwrap_or(0),
    );

    // `#pragma code_page` because the checkout can live under a path with characters
    // outside the ANSI code page, in which case rc.exe mangles the path and then
    // cannot find the file it was handed.
    let rc = format!(
        r#"#pragma code_page(65001)
1 ICON "{icon}"

1 VERSIONINFO
FILEVERSION {numeric}
PRODUCTVERSION {numeric}
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904b0"
        BEGIN
            VALUE "FileDescription", "Windows debloat tool\0"
            VALUE "FileVersion", "{version}\0"
            VALUE "ProductName", "debris\0"
            VALUE "ProductVersion", "{version}\0"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x0409, 1200
    END
END
"#
    );

    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is always set"));
    let rc_path = out.join("debris.rc");
    std::fs::write(&rc_path, rc).expect("writing the .rc should succeed");

    embed_resource::compile(&rc_path, embed_resource::NONE)
        .manifest_optional()
        .unwrap();
}

/// Writes `$OUT_DIR/bundle.rs`: the `assets/` and `scripts/` files the app reads at
/// runtime, as a table of `include_bytes!` entries.
///
/// Only what the app actually reads is embedded. `debris.ico` is left out because it is
/// a link-time resource (`1 ICON`, above) and never opened at runtime, and
/// `scripts/README.md` is left out because it documents the repository, not the app.
fn embed_runtime_data() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let assets = collect(&root.join("assets"), &["svg", "png", "txt", "json"]);
    let scripts = collect(&root.join("scripts"), &["ps1", "psm1"]);

    let mut out = String::from("// Generated by build.rs from `assets/` and `scripts/`. Do not edit.\n\n");
    out.push_str("/// One embedded file: the path it is known by, and its bytes.\n");
    out.push_str("pub struct File {\n    pub path: &'static str,\n    pub bytes: &'static [u8],\n}\n\n");
    table(&mut out, "ASSETS", &assets);
    table(&mut out, "SCRIPTS", &scripts);

    let path = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is always set"))
        .join("bundle.rs");
    std::fs::write(&path, out).expect("writing the bundle table should succeed");

    // A directory is enough: Cargo walks it, so an added or renamed file rebuilds.
    println!("cargo:rerun-if-changed={}", root.join("assets").display());
    println!("cargo:rerun-if-changed={}", root.join("scripts").display());
}

fn table(out: &mut String, name: &str, files: &[(String, PathBuf)]) {
    let _ = writeln!(out, "pub static {name}: &[File] = &[");
    for (key, path) in files {
        // The debug form of a path is a correctly escaped Rust string literal, which is
        // exactly what `include_bytes!` takes.
        let _ = writeln!(
            out,
            "    File {{ path: {key:?}, bytes: include_bytes!({path:?}) }},"
        );
    }
    let _ = writeln!(out, "];\n");
}

/// Every file under `base` whose extension is in `wanted`, as (path relative to `base`,
/// path on disk), sorted so the table — and the build — is deterministic.
///
/// Directories are walked rather than flattened, because the script library's shared
/// module is imported through `$PSScriptRoot` and the tree has to survive the trip.
fn collect(base: &Path, wanted: &[&str]) -> Vec<(String, PathBuf)> {
    let mut found = Vec::new();
    walk(base, base, wanted, &mut found);
    found.sort();
    found
}

fn walk(root: &Path, dir: &Path, wanted: &[&str], out: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            walk(root, &path, wanted, out);
            continue;
        }
        let extension = path
            .extension()
            .and_then(|extension| extension.to_str())
            .unwrap_or_default()
            .to_ascii_lowercase();
        if !wanted.contains(&extension.as_str()) {
            continue;
        }
        if let Ok(relative) = path.strip_prefix(root) {
            out.push((relative.to_string_lossy().replace('\\', "/"), path));
        }
    }
}
